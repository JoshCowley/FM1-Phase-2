"""FM1 Phase 2 step 1 (drums): Braids' digital oscillator as a changed copy that only knows the drum models.

make_units.py (the rack firmware's and the bench's) writes two files from the checkout's braids/digital_oscillator.{h,cc}
(pichenettes/eurorack, MIT; the checkout itself is never edited):

    units/rack_drum_osc.h               the class DrumOscillator in namespace braids_drum, without the 16,384-byte `delay_lines_`
                                        union (the comb, Karplus-Strong, bowed, blown and fluted models' memory: the drum models never
                                        touch it), so one voice is about 0.5 KB instead of 16.9 KB
    units/mi_braids_drum_oscillator.cc  its code: Mutable's functions for KICK, SNARE, CYMBAL, STRUCK DRUM, STRUCK BELL, FILTERED NOISE,
                                        CLOCKED NOISE, PARTICLE NOISE and TWIN PEAKS NOISE, copied unchanged (the text between the
                                        function's first and last line is not edited), Render() and the two phase-increment helpers

Every other model in the copy's table renders silence (RenderNone), and its functions are not in the copy. The names change
(DigitalOscillator -> DrumOscillator, namespace braids -> braids_drum, which still reads braids' tables and helpers), so the copy and
the stock class live in one program. rack_host's check 12 proves the nine models' output is bit-identical to the stock class's.
The MIT notice stays at the top of both files (NOTICE.md)."""
import re

KEEP = ("RenderKick", "RenderSnare", "RenderCymbal", "RenderStruckDrum", "RenderStruckBell", "RenderFilteredNoise",
        "RenderClockedNoise", "RenderParticleNoise", "RenderTwinPeaksNoise")
HELPERS = ("ComputePhaseIncrement", "ComputeDelay", "Render")
NOTE = ("// Generated by make_drum_osc.py (FM1 Phase 2, step 1, drums) from pichenettes/eurorack's braids/digital_oscillator.%s (MIT):\n"
        "// the class renamed DrumOscillator in namespace braids_drum, the delay-line union and every model but the nine drum models left\n"
        "// out. The functions kept are Mutable's, unchanged. The MIT notice below is the original's.\n")


def _sub(text, old, new, count=1):
    assert text.count(old) == count, "make_drum_osc: braids/digital_oscillator changed: " + old[:50]
    return text.replace(old, new)


def make(eur):
    h = (eur / "braids" / "digital_oscillator.h").read_text()
    c = (eur / "braids" / "digital_oscillator.cc").read_text()
    # ---- the header: the stock header is included (the constants, the shape enum and the models' state structs are braids' own),
    # and only the class is copied, as DrumOscillator, with the delay lines left out
    lic = h[:h.index("#ifndef BRAIDS_DIGITAL_OSCILLATOR_H_")]
    cls = h[h.index("class DigitalOscillator {"):h.index("}  // namespace braids")]
    a = cls.index("  union {\n    int16_t comb[kCombDelayLength];")
    z = cls.index("  } delay_lines_;") + len("  } delay_lines_;")
    cls = cls[:a] + "  // (no delay lines: the drum models do not use them)" + cls[z:]
    cls = _sub(cls, "  // void RenderYourAlgo(const uint8_t*, int16_t*, size_t);", "  void RenderNone(const uint8_t*, int16_t*, size_t);")
    cls = _sub(cls, "  static RenderFn fn_table_[];", "  static const RenderFn fn_table_[];   // (const: in flash; the stock class's table sits in RAM, 280 bytes)")
    cls = cls.replace("DigitalOscillatorShape", "@SHAPE@").replace("DigitalOscillatorState", "@STATE@").replace("DigitalOscillator", "DrumOscillator")
    cls = cls.replace("@SHAPE@", "DigitalOscillatorShape").replace("@STATE@", "DigitalOscillatorState")
    h = (lic + "#ifndef RACK_DRUM_OSCILLATOR_H_\n#define RACK_DRUM_OSCILLATOR_H_\n\n#include \"braids/digital_oscillator.h\"\n\n"
         "namespace braids_drum {\nusing namespace braids;\n\n" + cls + "}  // namespace braids_drum\n\n#endif  // RACK_DRUM_OSCILLATOR_H_\n")
    # ---- the code
    lines = c.split("\n")
    out, i, n = [], 0, len(lines)
    fn_re = re.compile(r"^(?:void|uint32_t|int16_t)\s+DigitalOscillator::(\w+)\(")
    seen = set()
    while i < n:
        m = fn_re.match(lines[i])
        if not m:
            out.append(lines[i]); i += 1; continue
        name = m.group(1)
        j = i
        while lines[j] != "}":
            j += 1
        if name in KEEP or name in HELPERS:
            out.extend(lines[i:j + 1]); seen.add(name)
        i = j + 1
    c = "\n".join(out)
    assert seen == set(KEEP) | set(HELPERS), "make_drum_osc: functions missing: %s" % (set(KEEP) | set(HELPERS) - seen)
    # the table: the nine drum models where they are, RenderNone elsewhere
    a = c.index("/* static */\nDigitalOscillator::RenderFn DigitalOscillator::fn_table_[] = {")
    b = c.index("};", a) + 2
    orig = (eur / "braids" / "digital_oscillator.cc").read_text()
    t0 = orig.index("DigitalOscillator::RenderFn DigitalOscillator::fn_table_[] = {")
    ents = re.findall(r"^\s*&DigitalOscillator::(\w+),?\s*$", orig[t0:orig.index("};", t0)], re.M)
    assert len(ents) == 35, "make_drum_osc: the table has %d entries" % len(ents)
    tab = "/* static */\nconst DrumOscillator::RenderFn DrumOscillator::fn_table_[] = {\n" + \
          ",\n".join("  &DrumOscillator::%s" % (e if e in KEEP else "RenderNone") for e in ents) + "\n};\n"
    c = c[:a] + tab + c[b:]
    c = c.replace("DigitalOscillatorShape", "@SHAPE@").replace("DigitalOscillatorState", "@STATE@").replace("DigitalOscillator", "DrumOscillator")
    c = c.replace("@SHAPE@", "DigitalOscillatorShape").replace("@STATE@", "DigitalOscillatorState")
    c = _sub(c, '#include "braids/digital_oscillator.h"', '#include "rack_drum_osc.h"')
    c = _sub(c, "namespace braids {\n", "namespace braids_drum {\n\nusing namespace braids;\n")
    c = _sub(c, "}  // namespace braids", "void DrumOscillator::RenderNone(const uint8_t*, int16_t* buffer, size_t size) {\n  while (size--) *buffer++ = 0;\n}\n\n}  // namespace braids_drum")
    # the delay-line users are gone with their functions; Render()'s FM quantiser reads a braids table (found through the using-directive)
    return {"rack_drum_osc.h": (NOTE % "h") + h, "mi_braids_drum_oscillator.cc": (NOTE % "cc") + c}
