"""FM1 Phase 2 2.48: Plaits' wavetable engine as a sound source (WAVE, module 5), slimmed for the FM-1.

make_units.py (the rack firmware's and the bench's) writes two files from the checkout's plaits/dsp/engine/wavetable_engine.cc and
plaits/resources.cc (pichenettes/eurorack, MIT; the checkout itself is never edited):

    units/rack_wave_osc.h          the class rackwave::Osc: Plaits' 8 x 8 x 4 wave terrain with the engine's own arithmetic (the Hermite read of the
                                   integrated waves, the one-pole smoothing of the scan position, the quantised stepping, the differentiating output stage),
                                   but without Plaits' Engine base class, its buffer allocator and its 12-frame call: the engine renders a block of 48
                                   frames, mixes the eight waves round the scan position into ONE 128-point table once a block (and only when the
                                   position has moved), and reads that table once a sample (two tables, cross-faded, in a block where it moved).
                                   The original reads all eight waves for every sample: 32 table reads against 4 or 8 here.
    units/mi_plaits_wave_data.cc   the wave data: Plaits' wav_integrated_waves, 192 waves of 128 points (+ 4 wrap points), 50,688 bytes, copied
                                   unchanged (three banks of 64; the fourth bank is the same 192 waves in Plaits' fixed shuffle, no more data)

The MIT notice stays at the top of both files (NOTICE.md)."""
import re

NOTE_H = ("// Generated by make_wave_osc.py (FM1 Phase 2, 2.48) from pichenettes/eurorack's plaits/dsp/engine/wavetable_engine.{h,cc} (MIT): the engine's\n"
          "// scan, smoothing, quantising, Hermite read and differentiating output kept; the Engine base class, the allocator and Plaits' 12-frame call\n"
          "// replaced by a block that mixes the eight waves into one table (see make_wave_osc.py). The MIT notice below is the original's.\n")
NOTE_D = ("// Generated by make_wave_osc.py (FM1 Phase 2, 2.48) from pichenettes/eurorack's plaits/resources.cc (MIT): wav_integrated_waves copied unchanged\n"
          "// (as rackwave::kWaves). The MIT notice below is the original's.\n")

HDR = r'''
#ifndef RACK_WAVE_OSC_H_
#define RACK_WAVE_OSC_H_

#include <stdint.h>
#include <stddef.h>
#include <math.h>

namespace rackwave {

const int kNumBanks = 4;                   // 3 banks of Plaits' waves + the shuffled fourth
const int kNumWavesPerBank = 64;           // 8 x 8
const int kNumWaves = 192;                 // the waves in the data
const int kTableSize = 128;
const int kWaveLen = kTableSize + 4;       // + the wrap points the Hermite read needs
extern const int16_t kWaves[];             // kNumWaves x kWaveLen integrated waves (mi_plaits_wave_data.cc)

// the wave behind a (bank, X, Y) coordinate: banks 0-2 are the data in order, bank 3 is Plaits' shuffle (w = i * 101 % 192 with i the map index)
inline const int16_t* WaveAt(int bank, int x, int y) {
  int i = bank * kNumWavesPerBank + y * 8 + x;
  int w = bank == kNumBanks - 1 ? (i * 101) % kNumWaves : i;
  return kWaves + (size_t)w * kWaveLen;
}

// Plaits' Clamp: the fractional part of a position pushed to the ends, so a quantised scan steps from wave to wave
inline float QClamp(float x, float amount) {
  x = x - 0.5f; x *= amount;
  if (x < -0.5f) x = -0.5f; else if (x > 0.5f) x = 0.5f;
  return x + 0.5f;
}

inline float Hermite(const float* t, int32_t i, float f) {
  const float xm1 = t[i], x0 = t[i + 1], x1 = t[i + 2], x2 = t[i + 3];
  const float c = (x1 - xm1) * 0.5f;
  const float v = x0 - x1;
  const float w = c + v;
  const float a = w + v + (x2 - x0) * 0.5f;
  const float b_neg = w + a;
  return (((a * f) - b_neg) * f + c) * f + x0;
}

// The eight waves round (x, y, z) mixed into one table (the position as Plaits has it: x and y 0..7, z the bank 0..3). Linear, so the differentiated
// output is the differentiated mix of the eight, as in the original.
inline void MixTable(float x, float y, float z, bool quantise, float* table) {
  int xi = (int)x, yi = (int)y, zi = (int)z;
  float xf = x - (float)xi, yf = y - (float)yi, zf = z - (float)zi;
  if (quantise) { xf = QClamp(xf, 16.0f); yf = QClamp(yf, 16.0f); zf = QClamp(zf, 16.0f); }
  int z1 = zi + 1; if (z1 >= 4) z1 = 7 - z1;
  const float wx[2] = { 1.0f - xf, xf }, wy[2] = { 1.0f - yf, yf }, wz[2] = { 1.0f - zf, zf };
  const int zz[2] = { zi, z1 };
  for (int j = 0; j < kWaveLen; ++j) table[j] = 0.0f;
  for (int c = 0; c < 2; ++c) for (int b = 0; b < 2; ++b) for (int a = 0; a < 2; ++a) {
    float w = wx[a] * wy[b] * wz[c];
    if (w <= 0.0f) continue;
    const int16_t* s = WaveAt(zz[c], xi + a, yi + b);
    for (int j = 0; j < kWaveLen; ++j) table[j] += w * (float)s[j];
  }
}

class Osc {
 public:
  void Init() { phase_ = 0.0f; fresh_ = true; built_ = false; cur_ = 0; prev_f0_ = 0.00916667f; prev_in_ = 0.0f; lp_diff_ = 0.0f; lp_out_ = 0.0f;
                xp_ = yp_ = zp_ = x_ = y_ = z_ = 0.0f; tx_ = ty_ = tz_ = -1.0f; }
  void Strike() { phase_ = 0.0f; }
  // x01, y01, bank01: the scan position and the bank, 0..1; f0: the pitch as a fraction of the sample rate; lowpass 1 = open; out: size samples
  void Render(float f0, float x01, float y01, float bank01, bool quantise, float lowpass, float* out, size_t size) {
    const float q = quantise ? 1.0f : 0.0f;
    const float tx = x01 * 6.9999f, ty = y01 * 6.9999f, tz = bank01 * 3.0f;
    if (fresh_) { xp_ = x_ = tx; yp_ = y_ = ty; zp_ = z_ = tz; fresh_ = false; }
    // Plaits smooths the scan position twice: once a call (0.2, the bank 0.05, a call = 12 frames: here a block of 48 = four calls), then a per-sample
    // one-pole whose coefficient grows with the pitch (0.01 to 0.1; faster when quantised)
    xp_ += 0.5904f * (tx - xp_); yp_ += 0.5904f * (ty - yp_); zp_ += 0.1855f * (tz - zp_);
    float c = 2.0f * f0 * (4.0f - 3.0f * q);
    c = c < 0.01f ? 0.01f : c > 0.1f ? 0.1f : c;
    const float k = 1.0f - powf(1.0f - c, (float)size);   // the one-pole after `size` samples
    x_ += k * (xp_ - x_); y_ += k * (yp_ - y_); z_ += k * (zp_ - z_);
    float px = x_ < 0.0f ? 0.0f : x_ > 6.9999f ? 6.9999f : x_, py = y_ < 0.0f ? 0.0f : y_ > 6.9999f ? 6.9999f : y_, pz = z_ < 0.0f ? 0.0f : z_ > 3.0f ? 3.0f : z_;
    bool moved = !built_ || fabsf(px - tx_) > 2.0e-4f || fabsf(py - ty_) > 2.0e-4f || fabsf(pz - tz_) > 2.0e-4f;
    int a = cur_;
    if (moved) { a = cur_; cur_ ^= 1; MixTable(px, py, pz, quantise, tab_[cur_]); tx_ = px; ty_ = py; tz_ = pz; if (!built_) { built_ = true; a = cur_; } }
    const float* ta = tab_[a];
    const float* tb = tab_[cur_];
    const bool blend = a != cur_;
    const float inv = 1.0f / (float)size;
    for (size_t n = 0; n < size; ++n) {
      const float u = (float)(n + 1) * inv;
      const float fn = prev_f0_ + (f0 - prev_f0_) * u;
      const float gain = (1.0f / (fn * 131072.0f)) * (0.95f - fn);
      float cutoff = 128.0f * fn; if (cutoff > 1.0f) cutoff = 1.0f;
      phase_ += fn; if (phase_ >= 1.0f) phase_ -= 1.0f;
      const float p = phase_ * 128.0f;
      const int32_t pi = (int32_t)p; const float pf = p - (float)pi;
      float m = Hermite(ta, pi, pf);
      if (blend) { float m2 = Hermite(tb, pi, pf); m += (m2 - m) * u; }
      lp_diff_ += cutoff * ((m - prev_in_) - lp_diff_);   // Plaits' Differentiator
      prev_in_ = m;
      float o = lp_diff_ * gain;
      if (lowpass < 0.999f) {   // 2.48: LOWPASS, a one-pole that follows the pitch (1 open; the cutoff from one harmonic to sixty-four)
        float h = 1.0f + 63.0f * lowpass * lowpass, cc = 6.2831853f * fn * h; cc = cc > 1.0f ? 1.0f : cc;
        lp_out_ += cc * (o - lp_out_); o = lp_out_;
      } else lp_out_ = o;
      out[n] = o;
    }
    prev_f0_ = f0;
  }
  // the unmodulated shape of the wave as the screen shows it: 64 points of one cycle, the differentiated mix at the position, scaled to +-1
  static void View(float x01, float y01, float bank01, float* out64) {
    float t[kWaveLen];
    MixTable(x01 * 6.9999f, y01 * 6.9999f, bank01 * 3.0f, false, t);
    float d[64], pk = 1.0f;
    for (int i = 0; i < 64; ++i) { d[i] = t[2 * i + 2] - t[2 * i + 1]; float a = fabsf(d[i]); if (a > pk) pk = a; }
    for (int i = 0; i < 64; ++i) out64[i] = d[i] / pk;
  }
 private:
  float phase_, xp_, yp_, zp_, x_, y_, z_, tx_, ty_, tz_, prev_f0_, prev_in_, lp_diff_, lp_out_;
  bool fresh_, built_;
  int cur_;
  float tab_[2][kWaveLen];
};

}  // namespace rackwave

#endif  // RACK_WAVE_OSC_H_
'''


def make(eur):
    eng = (eur / "plaits" / "dsp" / "engine" / "wavetable_engine.cc").read_text()
    res = (eur / "plaits" / "resources.cc").read_text()
    lic = eng[:eng.index("#include")]
    lic = lic[:lic.index("// 8x8x3 wave terrain.")].rstrip() + "\n"
    assert "Permission is hereby granted" in lic and "Emilie Gillet" in lic, "make_wave_osc: plaits' wavetable_engine.cc changed"
    a = res.index("const int16_t wav_integrated_waves[] = {")
    b = res.index("};", a) + 2
    body = res[a:b].replace("const int16_t wav_integrated_waves[] = {", "const int16_t kWaves[] = {", 1)
    n = len(re.findall(r"-?\d+", body.split("{", 1)[1]))
    assert n == 192 * 132, "make_wave_osc: plaits' wave data changed (%d values)" % n
    h = NOTE_H + lic + HDR
    d = NOTE_D + lic + '\n#include "rack_wave_osc.h"\n\nnamespace rackwave {\n\n' + body + "\n\n}  // namespace rackwave\n"
    return {"rack_wave_osc.h": h, "mi_plaits_wave_data.cc": d}
