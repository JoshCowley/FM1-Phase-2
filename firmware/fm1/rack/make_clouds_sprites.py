"""Writes clouds_sprites.h: the const tables the CLOUDS picture (vis_clouds.c) draws from, so the device does no
per-pixel maths and no floating point in the picture's pixel loops. Alpha masks (0..255) for the glowing motes in two
softnesses and three sizes, the comet, the hollow ring; the ribbon's cross-section, a fade, a Gaussian, a sine table
and the hue ramp. Run: python3 make_clouds_sprites.py > clouds_sprites.h  (the header is committed; this is its source)."""
import math

out = []
def tab(name, vals, typ="uint8_t", per=16):
    out.append("static const %s %s[%d] = {" % (typ, name, len(vals)))
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(int(v)) for v in vals[i:i + per]) + ",")
    out.append("};")

def blob(n, sigma, core):
    r = n // 2
    v = []
    for y in range(n):
        for x in range(n):
            d = math.hypot(x - r, y - r) / r
            a = math.exp(-(d / sigma) ** 2) * (1.0 if d <= 1.0 else max(0.0, 1.0 - (d - 1.0) * 3.0))
            a += core * math.exp(-(d / (sigma * 0.35)) ** 2)
            v.append(min(255, round(255 * min(1.0, a))))
    return v

out.append("/* SPDX-License-Identifier: GPL-3.0 */")
out.append("/* FM1 Phase 2: licensed GPL-3.0, see LICENSE. GENERATED by make_clouds_sprites.py: do not edit. */")
for n, sh, ss in ((5, 0.55, 0.9), (9, 0.5, 0.85), (13, 0.5, 0.85), (19, 0.45, 0.8)):
    tab("SPR_H%d" % n, blob(n, sh, 0.55), per=n)        # crisp: a small bright core
    tab("SPR_S%d" % n, [round(x * 0.8) for x in blob(n, ss, 0.0)], per=n)   # soft: wide and dim
# the comet: 40 x 9, bright at the right (the head), a tail fading to the left
cw, ch = 40, 9
v = []
for y in range(ch):
    for x in range(cw):
        dy = (y - 4) / 4.0
        along = x / (cw - 1.0)
        w = 0.25 + 0.75 * along
        a = (along ** 2.2) * math.exp(-(dy / w) ** 2 * 1.6)
        a += 0.9 * math.exp(-(((x - 37) / 3.2) ** 2 + (dy / 0.55) ** 2))
        v.append(min(255, round(255 * min(1.0, a))))
tab("SPR_COMET", v, per=cw)
# the hollow ring (frozen head): 15 x 15, radius 6
v = []
for y in range(15):
    for x in range(15):
        d = math.hypot(x - 7, y - 7)
        v.append(min(255, round(255 * math.exp(-((d - 6.0) / 1.0) ** 2))))
tab("SPR_RING", v, per=15)
# the ribbon's cross-section over t = |dy| / half-height in 0..1.6 (64 steps): a body, a brighter edge
v = []
for i in range(64):
    t = i / 40.0
    a = 0.34 * math.exp(-(t * 1.1) ** 2) + 0.70 * math.exp(-((t - 1.0) / 0.20) ** 2) + 0.30 * math.exp(-(t / 0.08) ** 2)
    if t > 1.0: a *= math.exp(-(t - 1.0) * 5.0)
    v.append(min(255, round(255 * min(1.0, a))))
tab("PROF", v)
tab("FADE", [round(255 * math.exp(-i / 9.0)) for i in range(32)])          # the reflection under the ribbon, and halos
tab("GAUSS", [round(255 * math.exp(-(i / 11.0) ** 2)) for i in range(64)])  # a soft side: halo, curtains
tab("SIN256", [round(16383 * math.sin(2 * math.pi * i / 256)) for i in range(256)], "int16_t", 16)
# the hue ramp PITCH picks from: cool blue (down) .. pale neutral .. warm orange (up), 16 steps, r g b
ramp = [(70, 115, 255), (80, 135, 255), (95, 160, 255), (115, 180, 255), (140, 200, 255), (170, 215, 250), (200, 225, 245), (225, 228, 232),
        (240, 225, 205), (250, 210, 170), (255, 192, 135), (255, 172, 105), (255, 150, 82), (255, 132, 66), (255, 116, 56), (255, 100, 48)]
tab("HUE", [c for rgb in ramp for c in rgb], per=12)
print("\n".join(out))
