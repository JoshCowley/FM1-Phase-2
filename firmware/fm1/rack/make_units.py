"""fm1.toml's gen step: units/, one small C++ file per engine source, each including the real one, so fm1-base's
build.py (which takes its o2 units from inside the app's folder) compiles FM1 Rack's engine and the Mutable modules
the Lite firmware has, from where they are."""
from pathlib import Path
import os

HERE = Path(__file__).resolve().parent
ENG = HERE.parent.parent.parent / "engine"
LITE_OUT = ("elements/", "warps/", "marbles/", "plaits/")   # FM1 Phase 2: no Plaits (fm1.toml RACK_NO_PLAITS); no Clouds since 2.48

units = HERE / "units"
units.mkdir(exist_ok=True)
want = {}
for src in (ENG / "sources.txt").read_text().split():
    if not src.startswith(LITE_OUT):
        want["mi_" + src.replace("/", "_")] = f'#include "{src}"\n'
want["rack.cc"] = '#include "../../../../engine/rack.cc"\n'
want["grids_nodes.cc"] = '#include "../../../../engine/grids_nodes.cc"\n'
want["rt.cc"] = '#include "../../common/rt.cc"\n'
want["rk.cc"] = '#include "../../common/rk.cc"\n'
# Rings' chord table is never written but isn't declared const, so it sits in RAM (1.4 KB): the unit carries a copy of
# part.cc with the table made const (the same numbers, in flash). The Mutable source itself is left as it is.
import os
EUR = Path(os.environ["EURORACK"]) if os.environ.get("EURORACK") else HERE.parent.parent.parent.parent / "eurorack"
part = (EUR / "rings" / "dsp" / "part.cc").read_text()
assert part.count("\nfloat chords[kMaxPolyphony][11][8] = {") == 2, "make_units: Rings' part.cc changed"
import sys as _sys0
_sys0.path.insert(0, str(HERE.parent / "common"))
import make_mutable_slim   # 2.42: const tables and the withdrawn Braids shapes' code (RACK_BRAIDS_TRIM)
want["mi_rings_dsp_part.cc"] = ("// Generated by make_units.py: eurorack's rings/dsp/part.cc with its chord table and model gains const (in flash, not RAM)\n" +
                                make_mutable_slim.apply_list(part.replace("\nfloat chords[kMaxPolyphony][11][8] = {", "\nconst float chords[kMaxPolyphony][11][8] = {"),
                                                             make_mutable_slim.RINGS_PART, "rings/dsp/part.cc"))
hdrs = {}
for _k, _v in make_mutable_slim.files(EUR).items():
    if _k.startswith("mi_"):
        want[_k] = _v
    else:
        hdrs[_k] = _v
# (2.48: Clouds is gone: its granular_processor, correlator, resources and phase-vocoder units, and their changed copies, are not made; the reverb is its fx_engine.h and the engine's own reverb.h)

# FM1 Phase 2 step 1 (drums): Braids' digital oscillator as a changed copy that knows only the drum models (common/make_drum_osc.py): the header
# units/rack_drum_osc.h (the engine includes it; fm1.toml puts units/ on the include path) and the unit mi_braids_drum_oscillator.cc
import sys as _sys
_sys.path.insert(0, str(HERE.parent / "common"))
import make_drum_osc
_eur2 = Path(os.environ["EURORACK"]) if os.environ.get("EURORACK") else HERE.parent.parent.parent.parent / "eurorack"
_d = make_drum_osc.make(_eur2)
(units / "rack_drum_osc.h").write_text(_d["rack_drum_osc.h"])
want["mi_braids_drum_oscillator.cc"] = _d["mi_braids_drum_oscillator.cc"]

# 2.48: Plaits' wavetable engine as the WAVE source (common/make_wave_osc.py): the header units/rack_wave_osc.h (the engine includes it) and the data unit
import make_wave_osc
_w = make_wave_osc.make(_eur2)
(units / "rack_wave_osc.h").write_text(_w["rack_wave_osc.h"])
want["mi_plaits_wave_data.cc"] = _w["mi_plaits_wave_data.cc"]

# (MODFM1 ran Plaits' MODAL on 16 of its 24 modes here; FM1 Phase 2 has no Plaits, 14 Nov 2026)
for f in units.glob("*.cc"):
    if f.name not in want:
        f.unlink()
for f in list(units.rglob("*.h")):               # the changed headers (units/braids/..., ahead of the checkout's on the include path)
    if f.parent != units and str(f.relative_to(units)) not in hdrs:
        f.unlink()
for rel, text in hdrs.items():
    f = units / rel
    f.parent.mkdir(parents=True, exist_ok=True)
    if not f.exists() or f.read_text() != text:
        f.write_text(text)
for name, text in want.items():
    f = units / name
    if not f.exists() or f.read_text() != text:
        f.write_text(text)
print(f"units: {len(want)} C++ units")
