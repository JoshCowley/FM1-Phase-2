"""Writes modsum_cases.h: three factory presets whole (every call of their final state, the knob layer's set_macro_target too, which
cases.h does not carry), for the MODSUM group of the benchmark (the mod_sum precompute against the scan it replaced, 23 Nov 2026).
ROTARY ORGAN is the one with the most LFO routes (7 of 18 rows), TIDE PAD the heaviest (28 knob targets), SHIMMER PAD six LFO routes and 21 targets.
  python3 make_modsum_cases.py      (from this folder; the header is committed)"""
import json
import sys
from pathlib import Path
import make_cases as mc

HERE = Path(__file__).resolve().parent
NAMES = ["ROTARY ORGAN", "TIDE PAD", "SHIMMER PAD"]
ALL = "--all" in sys.argv       # modsum_all.h: every factory preset whole (the host-only tool bench_ir, BENCH_MSALL)
mc.FN["set_macro_target"] = 12
mc.KEYLEN["set_macro_target"] = 2


def op(c):
    if c[0] == "set_macro_target":   # k, idx, slot, param, depth, start, end, curve
        return (12, c[1], c[2], c[3] & 0xFF, c[4], float(c[5]), float(c[6]), float(c[7]), float(c[8]))
    return mc.op(c)


def main():
    data = {p["name"]: p for p in json.loads(mc.SRC.read_text())}
    out = ["// SPDX-License-Identifier: GPL-3.0", "/* Generated by make_modsum_cases.py from firmware/tests/presets-fm1-calls.json: do not edit. */",
           "/* An op: x, the ints y z w, then fn (make_cases.py FN; 12: set_macro_target, a = knob, b = entry, c = slot (as int8), d = param, x..w = depth, start, end, curve) and a..d. */", ""]
    table = []
    names = [p["name"] for p in json.loads(mc.SRC.read_text()) if p["name"] != "INIT"] if ALL else NAMES
    for name in names:
        ident = "OPS_MS_" + name.replace(" ", "_")
        out.append(f"static const bop_t {ident}[] = {{")
        st = mc.final_state([c for c in data[name]["calls"] if c[0] != "set_macro_target"])
        ops = list(st.values()) + [c for c in {(c[1], c[2]): c for c in data[name]["calls"] if c[0] == "set_macro_target"}.values()]
        for c in ops:
            o = op(c)
            out.append("    {%s, %d, %d, %d, %d, %d, %d, %d, %d}," % (mc.fnum(o[5]), *(int(v) for v in (o[6], o[7], o[8])), *o[:5]))
        out.append("};")
        table.append(f'    {{"{name}", {ident}, {len(ops)}, 4, 0}},')
    out += ["", "static const bpreset_t MSPRESETS[] = {", *table, "};", "#define NMSPRESETS %d" % len(names), "static const char *const MSNAMES[] = {" + ", ".join('"%s"' % n for n in names) + "};", ""]
    fn = "modsum_all.h" if ALL else "modsum_cases.h"
    (HERE / fn).write_text("\n".join(out))
    print(f"{fn}: {len(names)} presets")


if __name__ == "__main__":
    sys.exit(main())
