static inline uint8_t mulaw_encode(float x) {
  int s = (int)(x * 32767.0f); if (s > 32635) s = 32635; if (s < -32635) s = -32635;
  int sign = 0; if (s < 0) { s = -s; sign = 0x80; }
  s += 0x84;
  int exp = 7; for (int m = 0x4000; exp > 0 && !(s & m); m >>= 1) --exp;
  int man = (s >> (exp + 3)) & 0x0F;
  return (uint8_t)~(sign | (exp << 4) | man);
}

